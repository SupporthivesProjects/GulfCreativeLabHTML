<script>

(function () {
  const section = document.querySelector('#how');
  if (!section) return;

  const slider = section.querySelector('.gr4.car.scrl');
  const dots = [...section.querySelectorAll('.how-dots button')];

  if (!slider || !dots.length) return;

  const slides = [...slider.querySelectorAll('.sl-st')];

  if (!slides.length) return;

  function isMobile() {
    return window.matchMedia('(max-width: 767px)').matches;
  }

  function updateDots() {
    if (!isMobile()) return;

    const sliderLeft = slider.getBoundingClientRect().left;

    let activeIndex = 0;
    let smallestDistance = Infinity;

    slides.forEach((slide, index) => {
      const distance = Math.abs(
        slide.getBoundingClientRect().left - sliderLeft
      );

      if (distance < smallestDistance) {
        smallestDistance = distance;
        activeIndex = index;
      }
    });

    dots.forEach((dot, index) => {
      dot.classList.toggle('active', index === activeIndex);
      dot.setAttribute(
        'aria-current',
        index === activeIndex ? 'true' : 'false'
      );
    });
  }

  dots.forEach((dot, index) => {
    dot.addEventListener('click', () => {
      if (!isMobile()) return;

      slides[index].scrollIntoView({
        behavior: 'smooth',
        block: 'nearest',
        inline: 'start'
      });
    });
  });

  let scrollTimeout;

  slider.addEventListener('scroll', () => {
    if (!isMobile()) return;

    clearTimeout(scrollTimeout);

    scrollTimeout = setTimeout(updateDots, 50);
  }, { passive: true });

  window.addEventListener('resize', updateDots);

  updateDots();
})();

</script>